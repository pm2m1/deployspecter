"""EXPERIMENTAL: generate ``docs/experimental_mvp/protocol/APPROVAL_DASHBOARD.md`` from the repository.

    python research_tools/confirmatory/dashboard.py [--out FILE] [--check]

The dashboard is regenerated, never hand-edited. Every status comes from the forms as they are (``approvals.status``),
so a decision stays PROPOSED until each required role signs its own form. ``--check`` exits 1 if the file on disk
differs from what the repository would generate now.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import approvals as ap  # noqa: E402
import verify_amendment as va  # noqa: E402

OUT = ap.PROTOCOL / "APPROVAL_DASHBOARD.md"
ROLE_NAME = {"owner": "project owner", "curator": "label curator (independent)",
             "oracle_author": "oracle author (independent)", "oracle_reviewer": "oracle reviewer (independent)",
             "triage_reviewer_1": "triage reviewer 1 (independent)",
             "triage_reviewer_2": "triage reviewer 2 (independent)", "adjudicator": "adjudicator (independent)"}
V2_SECTIONS = {"6": "## #6:", "7": "## #7:", "8": "## #8:", "9": "## #9:", "14": "## #14:"}
EVIDENCE = {  # beyond the signed form lines; what shows the ruling was implemented
    "1": "the selection tool's per-candidate record of the chosen Django migration area, by file names only",
    "2": "the recorded Alembic head per candidate, from `revision`/`down_revision` headers only",
    "3": "the recorded PostgreSQL extra per candidate, applied to every candidate alike",
    "4": "the frozen count of eligible blind cases at the freeze; RA-Q3 reported descriptive if < 10",
    "5": "a hash-pinned tree for each fix commit and its first parent; release pairs labelled confounded",
    "19": "each case's labels carry the documentation citation of its rolling or blue-green contract",
    "21": "the recorded version-named migration area per candidate",
    "A4": "the recorded migration-applying module per framework, as metadata",
    "A5": "the selection tool's two content reads logged as metadata-level exposure",
    "10": "the onboarding ledger separating per-application adapter work from engine work",
    "11": "each case's notification-path judgment; excluded cases listed",
    "12": "a development Django application of comparable scale run through the Django seam",
    "13": "the runc restriction disclosed in every result",
    "15": "B, T, replicates, R, P and C fixed in the adoption commit (PROSPECTIVE_MUSE_PLAN.md §5)",
    "16": "zero model calls recorded for every deterministic arm",
    "17": "model-proposed invariants labelled exploratory in every report",
    "18": "the four development artefacts cited only as development evidence",
    "20": "each public case's exposure ledger says 'training-data exposure not excludable'",
    "22": "every confirmatory run's corroboration: compared, mismatched (must be 0) and unchecked, per type",
}


def v2_evidence(decision: str) -> str | None:
    head = V2_SECTIONS.get(decision)
    if head is None:
        return None
    lines = (ap.PROTOCOL / "DECISIONS_003_v2.md").read_text().splitlines()
    start = next(i for i, x in enumerate(lines) if x.startswith(head))
    ev = next((i for i in range(start, len(lines)) if lines[i].startswith("**Evidence:**")), None)
    if ev is None:
        return None
    end = next((i for i in range(ev + 1, len(lines)) if lines[i].startswith(("## ", "**Until"))), len(lines))
    return f"`DECISIONS_003_v2.md` L{ev + 1}–L{end}"


def blocking(d: ap.Decision, s: dict) -> list[str]:
    b = [f"a named, independent {ROLE_NAME[r]}" for r in d.roles if r != "owner"]
    b += s["gaps"]
    if d.id == "9":
        b.append("every other form signed; the adoption commit made (checklist steps 1–5)")
    if d.id in ("6", "19"):
        b.append("sealed cases submitted through corpus_intake.py and the registry frozen (checklist step 7)")
    if d.id in ("7", "11"):
        b.append("oracle specs encoded, reviewed and hashed into the freeze (checklist step 8)")
    if d.id == "8":
        b.append("at least one corrected-version violation to triage (none exists before runs)")
    if d.id == "15":
        b.append("fixed before the freeze; no change after any result")
    return b


def render() -> str:
    ds, fs = ap.decisions(), ap.forms()
    v = va.verify(ap.PROTOCOL, ap.REPO / "docs/research/live_stepping")
    rows, by = [], {}
    for d in ds:
        s = ap.status(d, fs)
        by[s["status"]] = by.get(s["status"], 0) + 1
        rows.append((d, s))
    out = ["# Amendment 003 approval dashboard (generated; do not edit)", "",
           "Generated by `research_tools/confirmatory/dashboard.py` from the repository's own register and forms. "
           "Regenerate it after any form changes; `--check` fails if this file is stale.", "",
           f"- **Candidate:** `AMENDMENT_003_ADOPTION_CANDIDATE.md`, sha256 `{v['candidate_sha256']}`; "
           f"integrity problems: {len(v['integrity_problems'])}; adoption: {v['adoption']}.",
           f"- **Decisions:** {len(ds)}; " + "; ".join(f"{k}: {n}" for k, n in sorted(by.items())) + ".",
           "- **Rule enforced in code** (`approvals.py`): a role is satisfied only by a signed row on its own form. "
           "The owner's form can't approve for the curator, the oracle author or reviewer, or the triage reviewers "
           "and adjudicator; nor may one person hold two independent roles, or a developer hold any.",
           "- **Nothing here is signed, adopted, registered or published.**", "",
           "| # | Responsible (every one must sign) | Form lines | Status |", "|---|---|---|---|"]
    for d, s in rows:
        lines = "; ".join(f"{v_['form'].replace('.md', '')} L{v_['line']}" for v_ in s["roles"].values())
        out.append(f"| #{d.id} | {', '.join(ROLE_NAME[r] for r in d.roles)} | {lines} | **{s['status']}** |")
    out += ["", "## Per decision", ""]
    for d, s in rows:
        out += [f"### #{d.id} ({d.group}): **{s['status']}**", "",
                f"Proposed ruling (register `DECISIONS_003_v3.md` L{d.register_line}; binding text: candidate "
                f"L{d.candidate_line}):", "", "> " + d.ruling.replace("\n", " "), "",
                f"- **Decider (register):** {d.decider_text}"]
        for r, x in s["roles"].items():
            sig = ", ".join(f"L{n}" for n in x["signature_lines"]) or "none"
            out.append(f"- **{ROLE_NAME[r]}:** `approval/{x['form']}` decision line L{x['line']}, ticked "
                       f"{x['ticked'] or 'nothing'}; signature row {sig}: {'signed' if x['signed'] else 'unsigned'}")
        ev = [f"each required role's signed form line ticked 'approve' against candidate sha256 "
              f"`{v['candidate_sha256'][:12]}…`"]
        if (x2 := v2_evidence(d.id)):
            ev.append(f"accepted, implemented and verified evidence as listed in {x2}")
        if d.id in EVIDENCE:
            ev.append(EVIDENCE[d.id])
        out.append("- **Required evidence:** " + "; ".join(ev))
        out.append("- **Blocking:** " + "; ".join(blocking(d, s)) if blocking(d, s) else
                   "- **Blocking:** only the owner's signature")
        out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap_ = argparse.ArgumentParser()
    ap_.add_argument("--out", type=Path, default=OUT)
    ap_.add_argument("--check", action="store_true")
    a = ap_.parse_args(argv)
    text = render()
    if a.check:
        same = a.out.exists() and a.out.read_text() == text
        print("up to date" if same else "STALE: regenerate")
        return 0 if same else 1
    a.out.write_text(text)
    print(f"{a.out}: sha256 {hashlib.sha256(text.encode()).hexdigest()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
