"""EXPERIMENTAL trusted fixture: a small ledger service written with the SQLAlchemy 2.x ORM on psycopg 3.

Not part of any blind corpus. It is written here, with its defect known, to check that the stepping prototype sees
and schedules real ORM calls: ``Session.get``, attribute changes flushed as UPDATEs, ``Session.add`` flushed as an
INSERT ... RETURNING, ``select(...)`` through ``Session.scalars``, ``Session.begin()``, explicit ``commit()`` and
``rollback()``, and the pool's checkout and return.

* ``withdraw``: reads the account, refuses an overdraft from the balance it read, writes ``balance - amount`` and an
  entry. The buggy build reads without a lock, so two concurrent withdrawals can both pass the check and one update is
  lost. The fixed build reads ``with_for_update=True``.
* ``deposit``: the same shape, in a ``Session.begin()`` block.
* ``transfer``: locks (fixed build) or reads (buggy build) both accounts in id order with ``select``, then moves money.

How the engine is bound, without patching SQLAlchemy or psycopg: ``create_engine("postgresql+psycopg://",
creator=...)`` with a creator that hands over the actor's one ``SteppedConnection`` exactly once, in the actor's
thread, and a ``StaticPool`` that keeps that connection for the whole invocation (the dedicated-connection mode). A
second DBAPI connection, a creator called from another thread, or a pooled connection used by another actor is
refused. ``use_native_hstore=False`` is required: with it on, the dialect's first connect calls psycopg's
``TypeInfo.fetch``, which builds a plain ``psycopg.Cursor`` and so bypasses ``cursor_factory`` (found by the server-log
corroboration, and kept as a test).
"""

from __future__ import annotations

import threading
from typing import Any

from sqlalchemy import BigInteger, ForeignKey, Identity, create_engine, select
from sqlalchemy.orm import DeclarativeBase, Mapped, Session, mapped_column
from sqlalchemy.pool import StaticPool

from ..stepping import Handler, Refused, SteppedConnection, normal_sql

SCHEMA = "mvp_orm"
AUTOCOMMIT = False  # SQLAlchemy manages transactions on a non-autocommit DBAPI connection

DDL = """
CREATE TABLE accounts (id integer PRIMARY KEY, owner text NOT NULL, opening bigint NOT NULL,
                       balance bigint NOT NULL);
CREATE TABLE entries (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      account_id integer NOT NULL REFERENCES accounts(id), delta bigint NOT NULL CHECK (delta <> 0));
"""


class Base(DeclarativeBase):
    pass


class Account(Base):
    __tablename__ = "accounts"
    id: Mapped[int] = mapped_column(primary_key=True)
    owner: Mapped[str]
    opening: Mapped[int] = mapped_column(BigInteger)
    balance: Mapped[int] = mapped_column(BigInteger)


class Entry(Base):
    __tablename__ = "entries"
    id: Mapped[int] = mapped_column(Identity(), primary_key=True)
    account_id: Mapped[int] = mapped_column(ForeignKey("accounts.id"))
    delta: Mapped[int] = mapped_column(BigInteger)


# ------------------------------------------------------------------ binding SQLAlchemy to the actor's connection


def bind_engine(conn: SteppedConnection, *, poolclass: Any = StaticPool, **engine_kw: Any) -> Any:
    """An Engine whose only DBAPI connection is the actor's stepped one. Supported customization only: a ``creator``
    and a pool class; nothing global is patched."""
    owner = threading.current_thread()
    handed: list[SteppedConnection] = []

    def creator() -> SteppedConnection:
        if threading.current_thread() is not owner:
            raise Refused("the engine's creator was called from another thread")
        if handed:
            raise Refused("the engine asked for a second DBAPI connection; only the actor's stepped connection exists")
        handed.append(conn)
        return conn

    kw: dict[str, Any] = {"use_native_hstore": False}
    kw.update(engine_kw)
    return create_engine("postgresql+psycopg://", creator=creator, poolclass=poolclass, **kw)


# ------------------------------------------------------------------ the handlers (real application code)


class InsufficientFunds(Exception):
    pass


def withdraw(session: Session, *, account_id: int, amount: int, lock: bool) -> dict[str, Any]:
    acct = session.get(Account, account_id, with_for_update=lock)
    if acct is None:
        session.rollback()
        return {"status": "no_account"}
    if acct.balance < amount:
        session.rollback()
        return {"status": "insufficient"}
    acct.balance = acct.balance - amount  # computed in Python from what the read returned
    entry = Entry(account_id=account_id, delta=-amount)
    session.add(entry)
    session.flush()
    entry_id = entry.id
    session.commit()
    return {"status": "ok", "entry": entry_id}


def deposit(session: Session, *, account_id: int, amount: int, lock: bool) -> dict[str, Any]:
    with session.begin():
        acct = session.get(Account, account_id, with_for_update=lock)
        if acct is None:
            raise LookupError(f"account {account_id}")
        acct.balance = acct.balance + amount
        session.add(Entry(account_id=account_id, delta=amount))
    return {"status": "ok"}


def transfer(session: Session, *, src: int, dst: int, amount: int, lock: bool) -> dict[str, Any]:
    if src == dst:
        return {"status": "same_account"}
    stmt = select(Account).where(Account.id.in_([src, dst])).order_by(Account.id)
    if lock:
        stmt = stmt.with_for_update()
    with session.begin():
        accounts = {a.id: a for a in session.scalars(stmt)}
        if len(accounts) != 2:
            raise LookupError("account")
        if accounts[src].balance < amount:
            raise InsufficientFunds(f"account {src}")
        accounts[src].balance = accounts[src].balance - amount
        accounts[dst].balance = accounts[dst].balance + amount
        session.add_all([Entry(account_id=src, delta=-amount), Entry(account_id=dst, delta=amount)])
    return {"status": "ok"}


def _entry(fn: Any, *, lock: bool, poolclass: Any = StaticPool) -> Any:
    """The service's request boundary: one engine bound to this invocation's connection, one Session."""
    def handler(conn: SteppedConnection, **args: Any) -> Any:
        engine = bind_engine(conn, poolclass=poolclass)
        try:
            with Session(engine) as session:
                return fn(session, lock=lock, **args)
        except InsufficientFunds:
            return {"status": "insufficient"}
    handler.__name__ = fn.__name__
    handler.__qualname__ = fn.__qualname__
    handler.__module__ = fn.__module__
    return handler


