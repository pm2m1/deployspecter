# The psycopg dialect's first-connect queries. They read session settings only.
DIALECT_SETUP = frozenset(normal_sql(t) for t in (
    "select pg_catalog.version()", "select current_schema()", "show transaction isolation level",
    "show standard_conforming_strings"))

_COLS = "accounts.id AS accounts_id, accounts.owner AS accounts_owner, accounts.opening AS accounts_opening, " \
        "accounts.balance AS accounts_balance"
GET = f"SELECT {_COLS} FROM accounts WHERE accounts.id = %(pk_1)s::INTEGER"
GET_LOCKED = GET + " FOR UPDATE"
SELECT_PAIR = ("SELECT accounts.id, accounts.owner, accounts.opening, accounts.balance FROM accounts "
               "WHERE accounts.id IN (%(id_1_1)s::INTEGER, %(id_1_2)s::INTEGER) ORDER BY accounts.id")
SELECT_PAIR_LOCKED = SELECT_PAIR + " FOR UPDATE"
UPDATE_BALANCE = "UPDATE accounts SET balance=%(balance)s::BIGINT WHERE accounts.id = %(accounts_id)s::INTEGER"
INSERT_ENTRY = ("INSERT INTO entries (account_id, delta) VALUES (%(account_id)s::INTEGER, %(delta)s::BIGINT) "
                "RETURNING entries.id")
# The unit of work batches the two entries of a transfer into one statement ("insertmanyvalues").
INSERT_ENTRIES_2 = ("INSERT INTO entries (account_id, delta) SELECT p0::INTEGER, p1::BIGINT FROM (VALUES "
                    "(%(account_id__0)s::INTEGER, %(delta__0)s::BIGINT, 0), (%(account_id__1)s::INTEGER, "
                    "%(delta__1)s::BIGINT, 1)) AS imp_sen(p0, p1, sen_counter) ORDER BY sen_counter "
                    "RETURNING entries.id, entries.id AS id__1")
UPDATE_BALANCES_2 = UPDATE_BALANCE  # the unit of work issues one UPDATE per account (executemany when batched)


def _allow(*texts: str) -> frozenset[str]:
    return frozenset(normal_sql(t) for t in texts)


def registry(variant: str, *, poolclass: Any = StaticPool) -> dict[tuple[str, str], Handler]:
    if variant not in ("buggy", "fixed"):
        raise ValueError("variant must be buggy or fixed")
    lock = variant == "fixed"
    get = GET_LOCKED if lock else GET
    pair = SELECT_PAIR_LOCKED if lock else SELECT_PAIR
    money = {"account_id": int, "amount": int}
    handlers = [
        Handler("v1", "withdraw", _entry(withdraw, lock=lock, poolclass=poolclass),
                _allow(get, UPDATE_BALANCE, INSERT_ENTRY), money, setup_sql=DIALECT_SETUP),
        Handler("v1", "deposit", _entry(deposit, lock=lock, poolclass=poolclass),
                _allow(get, UPDATE_BALANCE, INSERT_ENTRY), money, setup_sql=DIALECT_SETUP),
        Handler("v1", "transfer", _entry(transfer, lock=lock, poolclass=poolclass),
                _allow(pair, UPDATE_BALANCE, INSERT_ENTRIES_2), {"src": int, "dst": int, "amount": int},
                setup_sql=DIALECT_SETUP),
    ]
    return {(h.app_version, h.name): h for h in handlers}


# ------------------------------------------------------------------ state: reset, independent read, oracle


def reset(conn: Any, seed: dict[str, list[dict[str, Any]]]) -> None:
    """Rebuild the schema and insert the seed, on a plain admin connection (never a stepped one)."""
    with conn.transaction():
        conn.execute(f"DROP SCHEMA IF EXISTS {SCHEMA} CASCADE")
        conn.execute(f"CREATE SCHEMA {SCHEMA}")
        conn.execute(f"SET LOCAL search_path = {SCHEMA}")
        conn.execute(DDL)
        for a in seed.get("accounts", []):
            conn.execute("INSERT INTO accounts (id, owner, opening, balance) VALUES (%s, %s, %s, %s)",
                         (a["id"], a["owner"], a["opening"], a["balance"]))


STATE_SQL = {"accounts": f"SELECT id, owner, opening, balance FROM {SCHEMA}.accounts ORDER BY id",
             "entries": f"SELECT id, account_id, delta FROM {SCHEMA}.entries ORDER BY id"}


def read_state(conn: Any) -> dict[str, list[dict[str, Any]]]:
    out: dict[str, list[dict[str, Any]]] = {}
    with conn.transaction():
        conn.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY")
        for table, text in STATE_SQL.items():
            cur = conn.execute(text)
            names = [d.name for d in cur.description]
            out[table] = [dict(zip(names, row, strict=True)) for row in cur.fetchall()]
    return out


def expected_initial(seed: dict[str, list[dict[str, Any]]]) -> dict[str, list[dict[str, Any]]]:
    return {"accounts": [{"id": a["id"], "owner": a["owner"], "opening": a["opening"], "balance": a["balance"]}
                         for a in sorted(seed.get("accounts", []), key=lambda a: a["id"])],
            "entries": []}


def check(state: dict[str, list[dict[str, Any]]]) -> list[str]:
    """From the specification: L1 a balance is its opening plus its entries; L2 no balance is negative."""
    sums: dict[int, int] = {}
    for e in state["entries"]:
        sums[e["account_id"]] = sums.get(e["account_id"], 0) + e["delta"]
    out = []
    for a in state["accounts"]:
        if a["balance"] != a["opening"] + sums.get(a["id"], 0):
            out.append(f"L1 account {a['id']}: balance {a['balance']} but opening {a['opening']} plus entries "
                       f"{sums.get(a['id'], 0)}")
        if a["balance"] < 0:
            out.append(f"L2 account {a['id']}: balance {a['balance']} is negative")
    return out
